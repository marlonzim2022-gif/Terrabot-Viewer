"use strict";
const versionSelect=document.getElementById("version");
const replaySelect=document.getElementById("replay");
const video=document.getElementById("video");
const empty=document.getElementById("empty");
const title=document.getElementById("title");
const status=document.getElementById("status");
const description=document.getElementById("description");
const metrics=document.getElementById("metrics");
let manifest=[];
const safePercent=value=>Number.isFinite(value)?Math.round(value*100)+"%":"—";
function renderReplay(){
 const version=manifest.find(x=>x.id===versionSelect.value);
 const replay=version?.replays?.find(x=>x.file===replaySelect.value);
 video.hidden=!replay;empty.hidden=!!replay;
 if(!replay){title.textContent="Nenhuma gravação";description.textContent="";status.textContent="";video.removeAttribute("src");return;}
 title.textContent=replay.label;description.textContent=replay.description||"";
 status.textContent="Replay animado";
 // Paths are generated by our own manifest, never from user input.
 video.src="media/"+encodeURIComponent(replay.file);
 video.onerror=()=>{video.hidden=true;empty.hidden=false;status.textContent="Gravação indisponível";};
 video.onload=()=>{video.hidden=false;empty.hidden=true;};
}
function renderVersion(){
 const version=manifest.find(x=>x.id===versionSelect.value);
 replaySelect.replaceChildren();
 for(const replay of version?.replays||[]){const option=document.createElement("option");option.value=replay.file;option.textContent=replay.label;replaySelect.append(option);}
 metrics.replaceChildren();
 for(const [label,value] of Object.entries(version?.metrics||{})){const cell=document.createElement("div");cell.className="metric";const big=document.createElement("b");big.textContent=safePercent(value);const small=document.createElement("span");small.textContent=label;cell.append(big,small);metrics.append(cell);}
 renderReplay();
}
async function init(){
 try{
  const response=await fetch("manifest.json",{cache:"no-store"});if(!response.ok)throw Error("manifest unavailable");
  manifest=await response.json();
  for(const version of manifest){const option=document.createElement("option");option.value=version.id;option.textContent=version.label;versionSelect.append(option);}
  versionSelect.addEventListener("change",renderVersion);replaySelect.addEventListener("change",renderReplay);renderVersion();
 }catch(e){empty.hidden=false;video.hidden=true;empty.textContent="Não foi possível carregar os replays.";status.textContent="Erro";}
}
init();